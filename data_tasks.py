def build_tasks():
    tasks = []
    for i, g in enumerate(GAPS):
        cls = CARBON_CLASS[i]
        cat = "CK" if g["id"].startswith(("CCER", "ETS_", "CBAM", "CARBON_PASS")) else (
            "CM" if g["id"] in ("GREEN_CERTIFICATE_RULES", "DATA_INFRA",
                                "MONTE_CARLO", "ERROR_CORRELATION",
                                "SENSITIVITY_ANALYSIS", "PRODUCT_CARBON_STORAGE")
            else ("CA" if g["id"].startswith("ACTIVITY") or g["id"] == "CITY_ENERGY_BALANCE"
                  else ("CF" if g["id"].startswith(("EF_", "GWP_", "CARBON_DENSITY", "BLUE_CARBON"))
                        else "MP")))
        cd = CATS[cat]
        tasks.append({
            "id": "C%02d" % i, "cat": cat, "catName": cd[0],
            "name": g["t"], "mod": g["mod"], "rows": g["rows"], "gapId": g["id"],
            "exist": cls[0], "access": cls[1], "compute": cls[2], "trace": cls[3],
            "level": cls[4], "status": cls[5],
            "year": cd[1], "geo": cd[2],
            "primary": cd[3], "alt": cd[4], "method": cd[5], "note": "",
        })
    for e in ENERGY_TASKS:
        cd = CATS[e[1]]
        tasks.append({
            "id": e[0], "cat": e[1], "catName": cd[0],
            "name": e[2], "mod": "—", "rows": "—", "gapId": "",
            "exist": e[3], "access": e[4], "compute": e[5], "trace": e[6],
            "level": e[7], "status": e[8],
            "year": cd[1], "geo": cd[2],
            "primary": cd[3], "alt": cd[4], "method": cd[5], "note": e[9],
        })
    return tasks


def validate(tasks):
    ids = [t["id"] for t in tasks]
    assert len(set(ids)) == len(ids), "任务编号重复"
    for t in tasks:
        assert t["exist"] in ("有", "部分", "无"), t["id"]
        assert t["access"] in ("公开", "受限", "不可得"), t["id"]
        assert t["compute"] in ("直接", "需计算", "需模型", "不可"), t["id"]
        assert t["trace"] in ("一手", "二手", "无"), t["id"]
        assert t["level"] in ("L1", "L2", "L3"), t["id"]
        assert t["status"] in STATUS_META, t["id"]
        # 逻辑不变量
        if t["access"] == "不可得" and t["status"] == "可获取未取":
            raise AssertionError("%s：不可得却标为可获取未取" % t["id"])
        if t["exist"] == "无" and t["level"] == "L1":
            raise AssertionError("%s：不存在却标为官方直接数据" % t["id"])
        if t["trace"] == "无" and t["level"] == "L1":
            raise AssertionError("%s：无法追溯却标 L1" % t["id"])
    from collections import Counter
    return {
        "total": len(tasks),
        "byStatus": dict(Counter(t["status"] for t in tasks)),
        "byLevel": dict(Counter(t["level"] for t in tasks)),
        "byExist": dict(Counter(t["exist"] for t in tasks)),
        "byAccess": dict(Counter(t["access"] for t in tasks)),
        "byCompute": dict(Counter(t["compute"] for t in tasks)),
        "byTrace": dict(Counter(t["trace"] for t in tasks)),
        "byCat": dict(Counter(t["catName"] for t in tasks)),
        "carbon": sum(1 for t in tasks if t["id"].startswith("C")),
        "energy": sum(1 for t in tasks if t["id"].startswith("E")),
    }


TASKS = build_tasks()
SUMMARY = validate(TASKS)


