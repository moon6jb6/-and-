    out = []
    for no, name, sub, accent, mods in LAYERS:
        for mname, rows, chips in mods:
            for g in MODULE_DETAIL[mname]["gaps"]:
                out.append({"layer": no, "mod": mname, "rows": rows,
                            "id": g[1], "t": g[0]})
    return out


