def build_data():
    # ---- 双轴标定 + 派生态 ----
    mod_names = [m[0] for _, _, _, _, mods in LAYERS for m in mods]
    missing = [n for n in mod_names if n not in AXES]
    assert not missing, "模块缺双轴标定: %s" % missing

    derived = {}
    for n in mod_names:
        M, D = AXES[n]
        d = MODULE_DETAIL[n]
        st = derive_status(M, D, len(d["gaps"]))
        # 不变量：数据不完备则必须有缺口清单
        if D < 4:
            assert len(d["gaps"]) >= 1, "D<4 却无缺口: %s (D=%d)" % (n, D)
        # 不变量：已核实状态不得留有缺口
        if st == "verified":
            assert len(d["gaps"]) == 0, "verified 却有缺口: %s" % n
        # 不变量：D0/D1 不得自称能出数
        derivation = (M, D, st)
        derived[n] = derivation

    # ---- 逐参数证据解析 ----
    ev = {}
    for mod, frag, sid, yr, unit, scope in EVIDENCE:
        assert mod in MODULE_DETAIL, "EVIDENCE 模块不存在: %s" % mod
        assert sid in SOURCES, "EVIDENCE 来源不存在: %s" % sid
        ev.setdefault(mod, []).append((frag, sid, yr, unit, scope))

    params_list = []
    used = set()
    for no, lname, sub, accent, mods in LAYERS:
        for mname, rows, chips in mods:
            frags = ev.get(mname, [])
            for txt in MODULE_DETAIL[mname]["verified"]:
                hit = None
                for i, f in enumerate(frags):
                    if f[0] in txt:
                        hit = i
                        break
                if hit is not None:
                    f = frags[hit]
                    used.add((mname, hit))
                    params_list.append({"layer": no, "mod": mname, "t": txt,
                                        "src": f[1], "year": f[2], "unit": f[3],
                                        "scope": f[4], "bound": True})
                else:
                    params_list.append({"layer": no, "mod": mname, "t": txt,
                                        "src": "", "year": "", "unit": "",
                                        "scope": UNBOUND_NOTE, "bound": False})
    _unused = [(m, fs[i][0]) for m, fs in ev.items()
               for i in range(len(fs)) if (m, i) not in used]
    assert not _unused, "EVIDENCE 片段未匹配到任何参数: %s" % _unused
    n_bound = sum(1 for p in params_list if p["bound"])

    layers = []
    for no, name, sub, accent, mods in LAYERS:
        ms = []
        for mname, rows, chips in mods:
            d = MODULE_DETAIL[mname]
            M, D, st = derived[mname]
            ms.append({
                "name": mname, "rows": rows,
                "chips": [{"n": n, "t": t} for n, t in chips],
                "status": st, "M": M, "D": D,
                "first": d["first"], "formula": d["formula"],
                "verified": d["verified"],
                "gaps": [{"t": g[0], "id": g[1]} for g in d["gaps"]],
                "srcs": d.get("srcs", []),
            })
        layers.append({"no": no, "name": name, "sub": sub, "accent": accent,
                       "first": LAYER_FIRST[no], "mods": ms})

    total_gaps = sum(len(MODULE_DETAIL[n]["gaps"]) for n in mod_names)
    total_params = sum(len(MODULE_DETAIL[n]["verified"]) for n in mod_names)
    cnt = {"verified": 0, "partial": 0, "pending": 0}
    for n in mod_names:
        cnt[derived[n][2]] += 1

    # ---- 全局断言 ----
    all_items = []
    for _, _, _, _, mods in LAYERS:
        for _, _, chips in mods:
            for num, _ in chips:
                all_items.append(int(num))
    assert len(all_items) == 137, len(all_items)
    assert sorted(all_items) == list(range(1, 138)), "行号不连续"
    assert len(mod_names) == 26, len(mod_names)
    assert len(LAYERS) == 8, len(LAYERS)
    assert cnt["verified"] + cnt["partial"] + cnt["pending"] == 26

    data = {
        "version": VERSION,
        "built": BUILT,
        "keyFigures": KEY_FIGURES,
        "layers": layers,
        "statusMeta": STATUS_META,
        "axes": {"M": [{"k": k, "code": c, "t": t} for k, c, t in STATUS_AXES["M"]],
                 "D": [{"k": k, "code": c, "t": t} for k, c, t in STATUS_AXES["D"]]},
        "sources": SOURCES,
        "units": [{"k": u[0], "a": u[1], "b": u[2]} for u in UNITS],
        "elec": ELEC_SERIES,
        "ets": ETS_2026,
        "ccer": {"ledger": CCER_LEDGER, "rules": CCER_RULES},
        "methods": METHODS,
        "identities": IDENTITIES,
        "params": params_list,
        "unboundNote": UNBOUND_NOTE,
        "totals": {"items": 137, "mods": 26, "layers": 8,
                   "gaps": total_gaps, "params": total_params,
                   "paramsBound": n_bound,
                   "paramsUnbound": total_params - n_bound,
                   "byStatus": cnt},
    }
    return data


